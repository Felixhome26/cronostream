import { useEffect, useMemo, useState } from "react";
import { getVersion } from "@tauri-apps/api/app";
import { openUrl } from "@tauri-apps/plugin-opener";
import { t } from "../../i18n";
import { useTheme } from "../../theme";
import {
  DOWNLOAD_URL,
  isAutoUpdateCheckOn,
  runManualUpdateCheck,
  setAutoUpdateCheck,
  type ManualCheckResult,
} from "../../utils/updateCheck";
import PreferencesGroup from "./settings/PreferencesGroup";
import PreferencesRow, { ToggleRow } from "./settings/PreferencesRow";

interface LicenseEntry {
  name: string;
  version: string;
  license: string;
  url: string;
  /// Keys into `LicenseData.texts`.
  texts: string[];
}

interface LicenseData {
  groups: { id: string; entries: LicenseEntry[] }[];
  texts: Record<string, string>;
}

/// Where the source code is published. The EUPL (Art. 3) asks for this
/// notice next to the copyright; keep in sync with the "own" entry in
/// scripts/generate-third-party-licenses.mjs.
const SOURCE_URL = "https://github.com/Felixhome26/cronostream";

/// Settings → About: version, copyright, and every third-party component
/// with its full license text. The list is generated by
/// `scripts/generate-third-party-licenses.mjs` and only fetched when the
/// dialog is opened (it's several hundred KB).
export default function AboutPanel() {
  const [version, setVersion] = useState<string>("");
  const logoSrc = useTheme() === "light" ? "/favicon_light.png" : "/favicon.png";
  const [open, setOpen] = useState(false);

  useEffect(() => {
    getVersion()
      .then(setVersion)
      .catch(() => setVersion(""));
  }, []);

  return (
    <section className="prefs-group">
      <div className="prefs-group__box">
        <div className="settings-row about-row">
          <img className="about-row__logo" src={logoSrc} alt="" />
          <span className="settings-row__text">
            <span className="settings-row__label">
              CronoStream{version ? ` ${version}` : ""}
            </span>
            <span className="settings-row__hint">{t("about.copyright")}</span>
            <span className="settings-row__hint">{t("about.disclaimer")}</span>
            <span className="settings-row__hint">
              {t("about.source")}{" "}
              <a
                href={SOURCE_URL}
                onClick={(ev) => {
                  ev.preventDefault();
                  openUrl(SOURCE_URL).catch(() => {});
                }}
              >
                {SOURCE_URL.replace(/^https:\/\//, "")}
              </a>
            </span>
            <span className="settings-row__hint">{t("about.openSource")}</span>
          </span>
          <button className="btn" onClick={() => setOpen(true)}>
            {t("about.showLicenses")}
          </button>
        </div>
      </div>
      <UpdateGroup />
      {open && <LicensesDialog onClose={() => setOpen(false)} />}
    </section>
  );
}

/// The switch for the automatic check and the manual check. Only this manual
/// one reports a failure; the automatic one stays silent when offline.
function UpdateGroup() {
  const [auto, setAuto] = useState(isAutoUpdateCheckOn);
  const [checking, setChecking] = useState(false);
  const [result, setResult] = useState<ManualCheckResult | null>(null);

  async function checkNow() {
    setChecking(true);
    setResult(null);
    setResult(await runManualUpdateCheck());
    setChecking(false);
  }

  return (
    <PreferencesGroup title={t("update.group")}>
      <ToggleRow
        id="setting-auto-update-check"
        label={t("update.autoLabel")}
        hint={t("update.autoHint")}
        on={auto}
        onToggle={() => {
          setAutoUpdateCheck(!auto);
          setAuto(!auto);
        }}
      />
      <PreferencesRow
        label={t("update.checkLabel")}
        hint={
          result?.status === "current"
            ? t("update.upToDate")
            : result?.status === "newer"
              ? t("update.available").replace("{version}", result.version)
              : result?.status === "unreachable"
                ? t("update.unreachable")
                : undefined
        }
        control={
          result?.status === "newer" ? (
            <button className="btn" onClick={() => openUrl(DOWNLOAD_URL).catch(() => {})}>
              {t("update.download")}
            </button>
          ) : (
            <button className="btn" disabled={checking} onClick={() => void checkNow()}>
              {checking ? t("update.checking") : t("update.checkNow")}
            </button>
          )
        }
      />
    </PreferencesGroup>
  );
}

function LicensesDialog({ onClose }: { onClose: () => void }) {
  const [data, setData] = useState<LicenseData | null>(null);
  const [error, setError] = useState(false);
  const [query, setQuery] = useState("");
  const [expanded, setExpanded] = useState<string | null>(null);

  useEffect(() => {
    fetch("/third-party-licenses.json")
      .then((response) => (response.ok ? response.json() : Promise.reject(response.status)))
      .then(setData)
      .catch(() => setError(true));
  }, []);

  useEffect(() => {
    function onKeyDown(ev: KeyboardEvent) {
      if (ev.key !== "Escape") return;
      ev.stopPropagation();
      onClose();
    }
    window.addEventListener("keydown", onKeyDown, true);
    return () => window.removeEventListener("keydown", onKeyDown, true);
  }, [onClose]);

  const groups = useMemo(() => {
    if (!data) return [];
    const needle = query.trim().toLowerCase();
    return data.groups
      .map((group) => ({
        ...group,
        entries: needle
          ? group.entries.filter(
              (entry) => entry.name.toLowerCase().includes(needle) || entry.license.toLowerCase().includes(needle),
            )
          : group.entries,
      }))
      .filter((group) => group.entries.length > 0);
  }, [data, query]);

  return (
    <div className="record-modal" onClick={onClose}>
      <div className="record-modal__panel licenses-dialog" onClick={(ev) => ev.stopPropagation()}>
        <div className="record-modal__header">
          <div className="record-modal__title">{t("about.licensesTitle")}</div>
          <button className="icon-btn" onClick={onClose} title={t("record.close")} aria-label={t("record.close")}>
            ✕
          </button>
        </div>
        <div className="record-modal__explain">{t("about.licensesIntro")}</div>
        <div className="licenses-dialog__search">
          <input
            className="text-input"
            value={query}
            placeholder={t("about.search")}
            onChange={(ev) => setQuery(ev.target.value)}
            autoFocus
          />
        </div>
        <div className="licenses-dialog__list">
          {error && <div className="record-modal__error-text">{t("about.loadError")}</div>}
          {!data && !error && <div className="record-modal__hint">…</div>}
          {groups.map((group) => (
            <div key={group.id} className="licenses-dialog__group">
              <div className="licenses-dialog__group-title">
                {t(`about.group.${group.id}`)} <span className="licenses-dialog__count">{group.entries.length}</span>
              </div>
              {group.id === "programs" && <p className="licenses-dialog__note">{t("about.ffmpegNote")}</p>}
              {group.id === "appimage" && <p className="licenses-dialog__note">{t("about.appimageNote")}</p>}
              {group.entries.map((entry) => {
                const key = `${group.id}:${entry.name}@${entry.version}`;
                const isOpen = expanded === key;
                return (
                  <div key={key} className="licenses-dialog__entry">
                    <button
                      className="licenses-dialog__entry-head"
                      onClick={() => setExpanded(isOpen ? null : key)}
                      aria-expanded={isOpen}
                    >
                      <span className="licenses-dialog__name">
                        {entry.name}
                        {entry.version && <span className="licenses-dialog__version"> {entry.version}</span>}
                      </span>
                      <span className="licenses-dialog__license">{entry.license}</span>
                    </button>
                    {isOpen && data && (
                      <div className="licenses-dialog__body">
                        <div className="licenses-dialog__url">{entry.url}</div>
                        {entry.texts.map((id) => (
                          <pre key={id} className="licenses-dialog__text">
                            {data.texts[id]}
                          </pre>
                        ))}
                      </div>
                    )}
                  </div>
                );
              })}
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}
