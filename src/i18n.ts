const dictionaries: Record<Language, Dict> = { de, en, es };

export const LANGUAGES: Language[] = ["de", "en", "es"];

/// Each language's own name for itself — what the switcher shows, so a
/// person who can't read the current UI language still finds theirs.
export const LANGUAGE_NATIVE_NAMES: Record<Language, string> = {
  de: "Deutsch",
  en: "English",
  es: "Español",
};

/// One choice per computer, not per stream: the start screen has no
/// project to read it from, and the drop box window (same origin) shares it.
const LANGUAGE_STORAGE_KEY = "cronostream.language";

function isLanguage(value: unknown): value is Language {
  return typeof value === "string" && (LANGUAGES as string[]).includes(value);
}

function readStoredLanguage(): Language {
  try {
    const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (isLanguage(stored)) return stored;
  } catch {
    // Storage unavailable — fall through to the system language.
  }
  // First start: follow the system language, English for anything unsupported.
  const system = (typeof navigator !== "undefined" ? navigator.language : "").slice(0, 2).toLowerCase();
  return isLanguage(system) ? system : "en";
}

/// The backend phrases its own error and progress messages (see
/// `src-tauri/src/i18n.rs`) and needs to be told. Plain `invoke`, not the
/// busy-tracking wrapper: this is instant and must not flash the spinner.
function syncBackendLanguage(language: Language) {
  try {
    invoke("set_ui_language", { language }).catch(() => {});
  } catch {
    // Outside Tauri (browser test setups) `invoke` throws synchronously.
    // Either way backend messages just stay German; nothing else depends on it.
  }
}

let activeLanguage: Language = readStoredLanguage();
document.documentElement.lang = activeLanguage;
syncBackendLanguage(activeLanguage);

// No stored choice yet: `navigator.language` above was only a first guess.
// The OS's own setting (read in the backend) is the reliable one, so correct
// to it once it arrives — without storing it, as the user hasn't chosen.
try {
  if (localStorage.getItem(LANGUAGE_STORAGE_KEY) === null) {
    invoke<string | null>("system_language")
      .then((code) => {
        if (isLanguage(code) && localStorage.getItem(LANGUAGE_STORAGE_KEY) === null) applyLanguage(code);
      })
      .catch(() => {});
  }
} catch {
  // Storage or `invoke` unavailable (browser test setups): keep the guess.
}

const languageListeners = new Set<() => void>();

function applyLanguage(language: Language) {
  if (language === activeLanguage) return;
  activeLanguage = language;
  document.documentElement.lang = language;
  syncBackendLanguage(language);
  for (const listener of languageListeners) listener();
}

// The other window (main app vs. drop box) changed it.
window.addEventListener("storage", (ev) => {
  if (ev.key === LANGUAGE_STORAGE_KEY && isLanguage(ev.newValue)) applyLanguage(ev.newValue);
});

/// The language the UI is currently running in. Read by anything that has
/// to produce language-specific *output* rather than just look up a string
/// — the hand-assembled date/time formatting in `utils/datetime.ts` in
/// particular. A getter rather than an exported const so callers can't
/// capture a stale value across a switch.
export function currentLanguage(): Language {
  return activeLanguage;
}

/// Switches the UI language and remembers it on this computer. `t()` is a
/// plain function, not a hook, so nothing re-renders by itself — the roots
/// subscribe via `useLanguage()` and remount their tree under a new key.
export function setLanguage(language: Language) {
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  } catch {
    // Not remembered, but still applied for this session.
  }
  applyLanguage(language);
}

function subscribeLanguage(listener: () => void): () => void {
  languageListeners.add(listener);
  return () => languageListeners.delete(listener);
}

/// The current language, re-rendering the caller whenever it changes.
export function useLanguage(): Language {
  return useSyncExternalStore(subscribeLanguage, currentLanguage);
}

export function t(key: string): string {
  return dictionaries[activeLanguage][key] ?? key;
}

// Maps a raw `timestamp_source` DB value (exif/fs_created/fs_modified/
// manual/ai) to its translated label — used anywhere that value is shown
// to the user, so an internal key like "fs_modified" never leaks into the
// UI untranslated. Falls back to the raw value for anything unmapped
// (safer than hiding it outright if a new source is ever added).
const SOURCE_LABEL_KEYS: Record<string, string> = {
  exif: "browser.review.sourceExif",
  meta: "browser.review.sourceMeta",
  filename: "browser.review.sourceFilename",
  fs_created: "browser.review.sourceCreated",
  fs_modified: "browser.review.sourceModified",
  manual: "browser.review.sourceManual",
  ai: "browser.review.sourceAi",
  recording: "browser.review.sourceRecording",
};

/// "1 Datei ausgewählt" / "3 Dateien ausgewählt": the number with the
/// singular or plural key, so a count of one never reads "1 Dateien".
export function tCount(count: number, oneKey: string, manyKey: string): string {
  return `${count} ${t(count === 1 ? oneKey : manyKey)}`;
}

export function timestampSourceLabel(source: string): string {
  const key = SOURCE_LABEL_KEYS[source];
  return key ? t(key) : source;
}

// The AI answers with the English values from its prompt ("high", "medium",
// "low"); shown in the UI language, the raw value for anything else.
const CONFIDENCE_LABEL_KEYS: Record<string, string> = {
  high: "browser.aiMetadata.confidenceHigh",
  medium: "browser.aiMetadata.confidenceMedium",
  low: "browser.aiMetadata.confidenceLow",
};

export function confidenceLabel(confidence: string): string {
  const key = CONFIDENCE_LABEL_KEYS[confidence];
  return key ? t(key) : confidence;
}
